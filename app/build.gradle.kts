import java.util.Properties
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

// Release signing is read from an untracked keystore.properties (see keystore.properties.example).
// Absent that file (local debug builds, CI without secrets), the release signingConfig is simply
// not wired up and `assembleRelease` produces an unsigned artifact rather than failing.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}
val hasReleaseSigning = keystoreProperties.getProperty("storeFile") != null

plugins {
    // AGP 9 has built-in Kotlin; the kotlin.android plugin is no longer applied.
    alias(libs.plugins.android.application)
    alias(libs.plugins.kotlin.compose)
    alias(libs.plugins.kotlin.serialization)
    alias(libs.plugins.ksp)
}

android {
    namespace = "com.enough.app"
    compileSdk = 36
    // Pin to an installed build-tools; no sdkmanager here to auto-download.
    buildToolsVersion = "36.1.0"

    defaultConfig {
        applicationId = "com.enough.app"
        minSdk = 26
        targetSdk = 35
        versionCode = 1
        versionName = "0.1.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        vectorDrawables { useSupportLibrary = true }
    }

    signingConfigs {
        if (hasReleaseSigning) {
            create("release") {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            // R8 in full mode; keep rules for serialization/Room/Compose live in proguard-rules.pro.
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
            // Only attach the release signingConfig when keystore.properties is present; otherwise
            // the release build stays unsigned (Play App Signing / manual signing can finish it).
            if (hasReleaseSigning) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }

    // Compile with the running JDK (21) but target Java 17 bytecode, so no
    // separate JDK-17 toolchain needs to be provisioned.
    kotlin {
        compilerOptions {
            jvmTarget.set(JvmTarget.JVM_17)
        }
    }

    testOptions {
        unitTests {
            isIncludeAndroidResources = true
            isReturnDefaultValues = true
        }
    }

    // Make the exported Room schemas available to Robolectric unit tests (which
    // read the debug variant's merged assets) so MigrationTestHelper can build old
    // schema versions and validate migrations. Scoped to debug: not shipped in release.
    sourceSets {
        getByName("debug").assets.srcDir("$projectDir/schemas")
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }
}

// Export the Room schema so migrations can be reviewed/tested as the DB evolves.
ksp {
    arg("room.schemaLocation", "$projectDir/schemas")
}

